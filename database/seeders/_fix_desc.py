def replace_gu_after(anchor: str, new: str) -> None:
    global src
    i = src.find(anchor)
    if i < 0:
        raise SystemExit("missing " + anchor)
    key = "'description_gu' => '"
    j = src.find(key, i)
    q1 = j + len(key) - 1
    q2 = src.find("'", q1 + 1)
    src = src[: q1 + 1] + new + src[q2:]
    print("ok", anchor[:36])


